#!/usr/bin/env python3
"""Generate lib/core/error_l10n.g.dart from @centurion/i18n errors.map.json.

Usage (from apps/mobile): python3 tool/gen_error_l10n.py && dart format lib/core/error_l10n.g.dart
Needs lib/l10n/gen (flutter gen-l10n) to resolve getter/method signatures.
"""
import json, os, re, sys, textwrap

_pins = open('lib/data/api/contracts_pin.dart').read()


def _git_or_file(pin_name, path):
    import subprocess
    pin = re.search(pin_name + r" = '([^']+)'", _pins).group(1)
    r = subprocess.run(['git', 'show', f'{pin}:{path}'], capture_output=True, text=True)
    return json.loads(r.stdout) if r.returncode == 0 else json.load(open('../../' + path))


# errors.map.json at i18nPin (or $ERRORS_MAP_JSON), never the working tree.
m = json.load(open(os.environ['ERRORS_MAP_JSON'])) if os.environ.get('ERRORS_MAP_JSON') else _git_or_file(
    'i18nPin', 'packages/i18n/errors.map.json')
# errors.json (Backend) may be ahead of errors.map.json (UX): those codes get an app-local fallback.
def _pinned_errors():
    if os.environ.get('ERRORS_JSON'):
        return json.load(open(os.environ['ERRORS_JSON']))
    return _git_or_file('contractsPin', 'packages/contracts/errors.json')


wire = [c['code'] for c in _pinned_errors()['codes']]
gen = open('lib/l10n/gen/app_localizations.dart').read()


def call(key):
    parts = re.split(r'[._]', key)
    g = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    if f'String get {g};' in gen:
        return g
    mm = re.search(rf'String {g}\(([^)]*)\);', gen)
    if not mm:
        sys.exit(f'missing l10n key {key} ({g})')
    args = []
    for p in mm.group(1).split(','):
        t, n = p.strip().split()
        wire = re.sub(r'([A-Z])', lambda x: '_' + x.group(1).lower(), n)
        args.append(f"'${{d['{wire}'] ?? ''}}'" if t == 'String' else f"(d['{wire}'] as num?)?.toInt() ?? 0")
    return f"{g}({', '.join(args)})"


def enum(code):
    p = code.lower().split('_')
    return p[0] + ''.join(x.title() for x in p[1:])


codes = dict(sorted(m['codes'].items()))
unk = m['unknown']['key'] if isinstance(m['unknown'], dict) else m['unknown']
J = '\n'.join
tones = [f"  ApiErrorCode.{enum(c)} => ErrorTone.{v['tone']}," for c, v in codes.items() if v.get('tone')]
titles = [f"  ApiErrorCode.{enum(c)} => l.{call(v['title_key'])}," for c, v in codes.items() if v.get('title_key')]
ctas = [f"  ApiErrorCode.{enum(c)} => l.{call(v['cta_key'])}," for c, v in codes.items() if v.get('cta_key')]
texts = [f"    ApiErrorCode.{enum(c)} => l.{call(v['key'])}," for c, v in codes.items()]
missing = sorted(set(wire) - set(codes))
fallback = (
    '    // App-local fallback for errors.json codes not in @centurion/i18n errors.map.json yet (UX owns the copy):\n'
    + ''.join(f'    // {ln}\n' for ln in textwrap.wrap(', '.join(missing) + '.', 100))
    + '    // Uses the errors.json catalog message (the same text the server sends).\n'
    + f'    _ => c.message(l.localeName) ?? l.{call(unk)},\n'
) if missing else ''
out = f"""// GENERATED by tool/gen_error_l10n.py from @centurion/i18n errors.map.json
// (errors_json_version {m['errors_json_version']}). Do not edit by hand; test/error_l10n_test.dart checks parity.

import '../data/api/api_exception.dart';
import '../l10n/gen/app_localizations.dart';

/// i18n `tone`: default error; `pending` (GUARD_WEAKEN_REQUIRES_APPROVAL is a
/// status, not a failure) and `warning` (QUOTE_MISSING_OR_STALE).
enum ErrorTone {{ error, warning, pending }}

ErrorTone errorTone(ApiErrorCode? c) => switch (c) {{
{J(tones)}
  _ => ErrorTone.error,
}};

String? errorTitle(AppLocalizations l, ApiErrorCode? c) => switch (c) {{
{J(titles)}
  _ => null,
}};

String? errorCta(AppLocalizations l, ApiErrorCode? c) => switch (c) {{
{J(ctas)}
  _ => null,
}};

/// Localized copy; placeholders come from `error.details` (snake_case).
String errorText(AppLocalizations l, ApiErrorCode? c, [Map<String, Object?> d = const {{}}]) {{
  return switch (c) {{
    null || ApiErrorCode.unknown => l.{call(unk)},
{J(texts)}
{fallback}  }};
}}

/// Codes with i18n copy (parity with errors.map.json). errors.json codes outside this list
/// render via the fallback in [errorText] until UX adds them to errors.map.json.
const errorL10nCodes = <String>[
{J(f"  '{c}'," for c in codes)}
];
"""
open('lib/core/error_l10n.g.dart', 'w').write(out)
print(f'error_l10n.g.dart: {len(codes)} codes; {len(missing)} without i18n copy (fallback): {missing}')
