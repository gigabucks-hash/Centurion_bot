def paint(size: int) -> Image.Image:
    radius, rows = MARKS[size]
    im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(im)
    draw.rounded_rectangle((0, 0, size - 1, size - 1), radius=radius, fill=INK)
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                px[x, y] = ORANGE
    return im


def main() -> None:
    icons = {size: paint(size) for size in MARKS}
    icons[48] = icons[24].resize((48, 48), Image.Resampling.NEAREST)
    web = REPO / "apps" / "web" / "public" / "brand"
    desk = REPO / "apps" / "desktop" / "src-tauri" / "icons"
    for size, im in icons.items():
        im.save(web / f"mark-{size}.png")
    icons[32].save(desk / "32x32.png")
    print("small", sorted(icons))


if __name__ == "__main__":
    main()
