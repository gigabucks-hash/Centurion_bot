-- Contracts 1.1.4: time-based exits (time_stop_s, stall_exit), exit_reason `stall`, and market cap on coins/picks.
-- Paper only: nothing here signs, holds keys or sends transactions.

-- `stall` = settings.stall_exit fired (|price change| over window_s < min_move_pct). `time_stop_s` reuses
-- `max_hold`. v1.0's `stall` maps to `no_new_high` (CHANGELOG 1.1.0) and keeps doing so.
alter type public.exit_reason add value if not exists 'stall';

-- Market cap (backend common::mcap; the same value the screener's mcap_usd metric uses).
-- market_cap_lamports: whole lamports; null when decimals or supply are unknown.
-- mcap_usd: display-only, indicative (configured SOL/USD reference, as for marks).
alter table public.coins
  add column market_cap_lamports numeric(39, 0) check (market_cap_lamports is null or market_cap_lamports >= 0),
  add column mcap_usd numeric check (mcap_usd is null or mcap_usd >= 0),
  add column mcap_as_of timestamptz,
  add constraint coins_mcap_as_of check ((market_cap_lamports is null and mcap_usd is null) or mcap_as_of is not null);
alter table public.picks
  add column market_cap_lamports numeric(39, 0) check (market_cap_lamports is null or market_cap_lamports >= 0),
  add column mcap_usd numeric check (mcap_usd is null or mcap_usd >= 0),
  add column mcap_as_of timestamptz,
  add constraint picks_mcap_as_of check ((market_cap_lamports is null and mcap_usd is null) or mcap_as_of is not null);

